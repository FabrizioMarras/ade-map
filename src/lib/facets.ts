export const FACET_LABELS: Record<FacetKey, string> = {
  genre: 'Genre',
  time: 'Time of day',
  venueType: 'Venue type',
  area: 'Area',
  type: 'Event type',
  other: 'Other',
};

export function facetOf(tag: string): FacetKey {
  return LOOKUP.get(tag) ?? 'other';
}

export function splitFacets(tags: string[]): Facets {
  const out: Facets = { genre: [], time: [], venueType: [], area: [], type: [], other: [] };
  for (const t of tags) {
    const f = facetOf(t);
    if (!out[f].includes(t)) out[f].push(t);
  }
  return out;
}
