const LOOKUP = new Map<string, Exclude<FacetKey, 'other'>>();
for (const [facet, tags] of Object.entries(TABLE) as [Exclude<FacetKey, 'other'>, string[]][]) {
  for (const t of tags) LOOKUP.set(t, facet);
}

export const FREE_TAGS = new Set(['Free Festival Events', 'Free A&C Events']);

/** Time-of-day filter labels shown in the UI. */
